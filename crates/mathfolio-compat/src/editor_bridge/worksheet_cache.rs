    fn pad_for_batch(source: &mut Vec<(u64, f64, f64, String)>) {
        while source.len() < MIN_BATCH_REGIONS {
            let i = source.len();
            source.push((
                100_000 + i as u64,
                0.,
                1000. + i as f64,
                define(&format!("batch_pad_{i}"), "<ml:real>0</ml:real>"),
            ));
        }
    }
    fn fragmentwise(
        cache: &mut WorksheetXmlCache,
        source: &[(u64, f64, f64, String)],
    ) -> Result<String, String> {
        worksheet_xml_with(
            source,
            |_, id, xml, definitions| cache.label(id, xml, definitions),
            None,
        )
    }
