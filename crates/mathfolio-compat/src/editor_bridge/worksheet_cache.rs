    #[test]
    #[ignore = "CPU-only uncached versus memoized worksheet labelling profile"]
    fn profile_cold_and_edited_worksheet_labelling() {
        use std::time::Instant;
        let mut cold_plain = Vec::new();
        let mut cold_cached = Vec::new();
        let mut edited_plain = Vec::new();
        let mut edited_cached = Vec::new();
        for round in 0..11 {
            let mut source = regions(
                &(0..4000)
                    .map(|i| define(&format!("v{i}"), &format!("<ml:real>{i}</ml:real>")))
                    .collect::<Vec<_>>(),
            );
            let mut cache = WorksheetXmlCache::default();
            // Alternate first position so a consistently warmer process path
            // does not silently favor either implementation.
            let (plain, cached) = if round % 2 == 0 {
                let start = Instant::now();
                let plain = worksheet_xml(&source).unwrap();
                cold_plain.push(start.elapsed().as_micros());
                let start = Instant::now();
                let cached = cache.build(&source).unwrap();
                cold_cached.push(start.elapsed().as_micros());
                (plain, cached)
            } else {
                let start = Instant::now();
                let cached = cache.build(&source).unwrap();
                cold_cached.push(start.elapsed().as_micros());
                let start = Instant::now();
                let plain = worksheet_xml(&source).unwrap();
                cold_plain.push(start.elapsed().as_micros());
                (plain, cached)
            };
            assert_eq!(plain, cached);
            source[0].3 = define("v0", "<ml:real>9</ml:real>");
            let start = Instant::now();
            let plain = worksheet_xml(&source).unwrap();
            edited_plain.push(start.elapsed().as_micros());
            let start = Instant::now();
            let cached = cache.build(&source).unwrap();
            edited_cached.push(start.elapsed().as_micros());
            assert_eq!(plain, cached);
        }
        let median = |samples: &mut Vec<u128>| {
            samples.sort_unstable();
            samples[samples.len() / 2]
        };
        println!(
            "LABEL_CACHE_PROFILE regions=4000 rounds=11 cold_plain_us={} cold_cached_us={} edited_plain_us={} edited_cached_us={}",
            median(&mut cold_plain),
            median(&mut cold_cached),
            median(&mut edited_plain),
            median(&mut edited_cached)
        );
    }
