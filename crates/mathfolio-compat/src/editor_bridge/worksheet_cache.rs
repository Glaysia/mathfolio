//! Exact source and identifier-context memoization. This caches labelling,
//! never evaluation, validity of a binding, or calculated worksheet results.
use super::*;

#[cfg(test)]
#[path = "worksheet_profile.rs"]
pub(super) mod profile;

const MAX_CACHED_BYTES: usize = 32 * 1024 * 1024;
// This is a cold-path opportunity, not a new acceptance budget. Larger inputs,
// parser resource limits, and malformed batch XML use the ordinary fragment
// path and its original validation/error order instead.
const MAX_BATCH_BYTES: usize = 2 * 1024 * 1024;
const MAX_BATCH_NODES: u32 = 100_000;
// Conservative workload eligibility, not an acceptance rule or a universal
// crossover point. Dense fragments keep the ordinary fragment path.
const MIN_BATCH_REGIONS: usize = 256;
const MAX_BATCH_AVERAGE_FRAGMENT: usize = 1024;
const MAX_BATCH_FRAGMENT: usize = 8 * 1024;

fn cold_batch_source(
    regions: &[(u64, f64, f64, String)],
) -> Option<(String, Vec<std::ops::Range<usize>>)> {
    let fragment_bytes = regions.iter().try_fold(0usize, |sum, region| {
        if region.3.len() > MAX_BATCH_FRAGMENT {
            return None;
        }
        sum.checked_add(region.3.len())
    })?;
    if fragment_bytes > regions.len().checked_mul(MAX_BATCH_AVERAGE_FRAGMENT)? {
        return None;
    }
    // roxmltree reserves node/attribute vectors from literal '<'/'=' counts
    // before enforcing nodes_limit. Bound those reserve hints as well.
    let mut node_hint = regions.len().checked_mul(2)?.checked_add(2)?;
    let mut attribute_hint = 2usize;
    for (_, _, _, xml) in regions {
        node_hint += xml.bytes().filter(|b| *b == b'<').count();
        attribute_hint += xml.bytes().filter(|b| *b == b'=').count();
        if node_hint > MAX_BATCH_NODES as usize || attribute_hint > MAX_BATCH_NODES as usize {
            return None;
        }
    }
    let opening = format!("<batch xmlns:ml=\"{ML}\" xmlns=\"{WS}\">");
    let bytes = regions
        .iter()
        .try_fold(opening.len() + "</batch>".len(), |sum, r| {
            sum.checked_add("<context></context>".len())?
                .checked_add(r.3.len())
        })?;
    if bytes > MAX_BATCH_BYTES {
        return None;
    }
    let mut source = String::with_capacity(bytes);
    source.push_str(&opening);
    let mut ranges = Vec::with_capacity(regions.len());
    for (_, _, _, xml) in regions {
        let start = source.len();
        source.push_str("<context>");
        source.push_str(xml);
        source.push_str("</context>");
        ranges.push(start..source.len());
    }
    source.push_str("</batch>");
    Some((source, ranges))
}

/// Byte offsets into the exact source returned by `GeneratedWorksheet`.
/// These are emitted by the builder, rather than recovered by parsing the
/// complete generated worksheet a second time.
pub struct GeneratedRegion {
    pub id: u64,
    pub left: std::ops::Range<usize>,
    pub top: std::ops::Range<usize>,
    pub math: Option<std::ops::Range<usize>>,
}

/// Optional per-region display result. A missing result denotes a cache hit or
/// a region without an ordinary math wrapper, not a calculation failure.
pub type DisplayProjection = Option<Result<PortableTree, String>>;

pub struct GeneratedWorksheet {
    pub(super) source: String,
    pub(super) regions: Vec<GeneratedRegion>,
    decoded_trees: Vec<DisplayProjection>,
}

impl GeneratedWorksheet {
    pub fn into_parts(self) -> (String, Vec<GeneratedRegion>) {
        (self.source, self.regions)
    }
    pub fn into_parts_with_trees(self) -> (String, Vec<GeneratedRegion>, Vec<DisplayProjection>) {
        (self.source, self.regions, self.decoded_trees)
    }
}

#[derive(Default)]
pub struct WorksheetXmlCache {
    entries: HashMap<u64, Fragment>,
    bytes: usize,
    #[cfg(test)]
    hits: usize,
    #[cfg(test)]
    batch_builds: usize,
    #[cfg(test)]
    batch_fallbacks: usize,
}

struct Fragment {
    source: String,
    dependencies: HashMap<String, Option<String>>,
    defined: Option<(String, String)>,
    labelled: String,
    bytes: usize,
}

impl WorksheetXmlCache {
    /// Same output and validation as worksheet_xml. Global declarations and
    /// geometric ordering always use the ordinary builder. A changed context
    /// only reuses fragments whose complete worksheet lookup set is equal.
    /// Explicit labels, structural labels and bound locals do not consult that
    /// environment; recording them would add cold allocations and invalidate
    /// fragments even when their output cannot change.
    pub fn build(&mut self, regions: &[(u64, f64, f64, String)]) -> Result<String, String> {
        self.build_with(regions, None, None, None, None)
    }

    /// The same validated source as `build`, accompanied by generated byte
    /// ranges. Namespace context remains the worksheet's fixed WS/ML context;
    /// additional namespaces stay in the labelled fragments themselves.
    pub fn build_prepared(
        &mut self,
        regions: &[(u64, f64, f64, String)],
    ) -> Result<GeneratedWorksheet, String> {
        let mut metadata = Vec::with_capacity(regions.len());
        let source = self.build_with(regions, Some(&mut metadata), None, None, None)?;
        Ok(GeneratedWorksheet {
            source,
            regions: metadata,
            decoded_trees: Vec::new(),
        })
    }

    /// Eager display trees from the already parsed, independently labelled
    /// contexts. Trees are moved into metadata, never retained by this cache.
    /// Hits leave the optional tree empty so callers can reuse their own exact
    /// display-source cache or take their ordinary decoder fallback.
    pub fn build_prepared_with_trees(
        &mut self,
        regions: &[(u64, f64, f64, String)],
    ) -> Result<GeneratedWorksheet, String> {
        let mut metadata = Vec::with_capacity(regions.len());
        let mut decoded: Vec<_> = (0..regions.len()).map(|_| None).collect();
        let source =
            self.build_with(regions, Some(&mut metadata), Some(&mut decoded), None, None)?;
        Ok(GeneratedWorksheet {
            source,
            regions: metadata,
            decoded_trees: decoded,
        })
    }

    /// Optional private-field proofs use a bounded typed label path. A proof
    /// must match the exact raw XML; mismatches and unsupported forms use DOM.
    pub fn build_prepared_with_typed_trees(
        &mut self,
        regions: &[(u64, f64, f64, String)],
        typed: &HashMap<u64, std::sync::Arc<TypedMathml>>,
    ) -> Result<GeneratedWorksheet, String> {
        let mut metadata = Vec::with_capacity(regions.len());
        let mut decoded: Vec<_> = (0..regions.len()).map(|_| None).collect();
        let source = self.build_with(
            regions,
            Some(&mut metadata),
            Some(&mut decoded),
            Some(typed),
            None,
        )?;
        Ok(GeneratedWorksheet {
            source,
            regions: metadata,
            decoded_trees: decoded,
        })
    }

    /// Operation-local serializer traces accelerate cold typed label emission.
    /// The ordinary proof API, cache ownership and all fallback paths remain.
    pub fn build_prepared_with_traced_trees(
        &mut self,
        regions: &[(u64, f64, f64, String)],
        typed: &HashMap<u64, std::sync::Arc<TypedMathml>>,
        mut traces: MathmlTraces,
    ) -> Result<GeneratedWorksheet, String> {
        traces.sort();
        let mut metadata = Vec::with_capacity(regions.len());
        let mut decoded = (0..regions.len()).map(|_| None).collect();
        let source = self.build_with(
            regions,
            Some(&mut metadata),
            Some(&mut decoded),
            Some(typed),
            Some(&traces),
        )?;
        Ok(GeneratedWorksheet {
            source,
            regions: metadata,
            decoded_trees: decoded,
        })
    }

    fn build_with(
        &mut self,
        regions: &[(u64, f64, f64, String)],
        metadata: Option<&mut Vec<GeneratedRegion>>,
        mut decoded: Option<&mut Vec<Option<Result<PortableTree, String>>>>,
        typed: Option<&HashMap<u64, std::sync::Arc<TypedMathml>>>,
        traces: Option<&MathmlTraces>,
    ) -> Result<String, String> {
        #[cfg(test)]
        let retain_timing = profile::scope(profile::Phase::Retain);
        let active: HashSet<_> = regions.iter().map(|r| r.0).collect();
        self.entries.retain(|id, entry| {
            if active.contains(id) {
                true
            } else {
                self.bytes -= entry.bytes;
                false
            }
        });
        #[cfg(test)]
        drop(retain_timing);
        if typed.is_none_or(|proofs| !proofs.values().any(|proof| proof.eligible()))
            && self.entries.is_empty()
            && regions.len() >= MIN_BATCH_REGIONS
        {
            #[cfg(test)]
            let parse_timing = profile::scope(profile::Phase::Parse);
            let batch = cold_batch_source(regions);
            if let Some((source, ranges)) = batch.as_ref() {
                let options = roxmltree::ParsingOptions {
                    nodes_limit: MAX_BATCH_NODES,
                    ..Default::default()
                };
                if let Ok(document) = roxmltree::Document::parse_with_options(source, options) {
                    let contexts: Vec<_> = document
                        .root_element()
                        .children()
                        .filter(Node::is_element)
                        .collect();
                    // An injected context delimiter must never change fragment
                    // boundaries or turn individually invalid XML into success.
                    if contexts.len() == regions.len()
                        && contexts.iter().zip(ranges).all(|(node, range)| {
                            node.has_tag_name((WS, "context")) && node.range() == *range
                        })
                    {
                        #[cfg(test)]
                        drop(parse_timing);
                        #[cfg(test)]
                        {
                            self.batch_builds += 1;
                        }
                        return worksheet_xml_with(
                            regions,
                            |index, id, xml, definitions| {
                                self.label_parsed(
                                    id,
                                    xml,
                                    contexts[index],
                                    source,
                                    definitions,
                                    decoded.as_mut().map(|rows| &mut rows[index]),
                                )
                            },
                            metadata,
                        );
                    }
                }
            }
            #[cfg(test)]
            drop(parse_timing);
            #[cfg(test)]
            {
                self.batch_fallbacks += 1;
            }
        }
        worksheet_xml_with(
            regions,
            |index, id, xml, definitions| {
                if let Some(proofs) = typed {
                    // A hit already proves source/context equality. Do not read
                    // the same large raw XML again merely to select a miss path.
                    if let Some(labelled) = self.lookup(id, xml, definitions) {
                        return Ok(labelled);
                    }
                    if let Some(proof) = proofs
                        .get(&id)
                        .filter(|proof| proof.eligible() && proof.source() == xml)
                    {
                        self.label_proven(
                            id,
                            xml,
                            proof,
                            definitions,
                            decoded.as_mut().map(|rows| &mut rows[index]),
                            traces.and_then(|traces| traces.get(id, proof)),
                        )
                    } else {
                        self.label_with_tree_miss(
                            id,
                            xml,
                            definitions,
                            decoded.as_mut().map(|rows| &mut rows[index]),
                        )
                    }
                } else {
                    self.label_with_tree(
                        id,
                        xml,
                        definitions,
                        decoded.as_mut().map(|rows| &mut rows[index]),
                    )
                }
            },
            metadata,
        )
    }

    #[cfg(test)]
    fn label(
        &mut self,
        id: u64,
        xml: &str,
        definitions: &mut HashMap<String, String>,
    ) -> Result<String, String> {
        self.label_with_tree(id, xml, definitions, None)
    }
    fn lookup(
        &mut self,
        id: u64,
        xml: &str,
        definitions: &mut HashMap<String, String>,
    ) -> Option<String> {
        {
            #[cfg(test)]
            let _timing = profile::scope(profile::Phase::Lookup);
            if let Some(entry) = self.entries.get(&id)
                && entry.source == xml
                && entry
                    .dependencies
                    .iter()
                    .all(|(name, label)| definitions.get(name) == label.as_ref())
            {
                if let Some((name, label)) = &entry.defined {
                    definitions.insert(name.clone(), label.clone());
                }
                #[cfg(test)]
                {
                    self.hits += 1;
                }
                return Some(entry.labelled.clone());
            }
        }
        None
    }

    fn label_proven(
        &mut self,
        id: u64,
        xml: &str,
        proof: &TypedMathml,
        definitions: &mut HashMap<String, String>,
        decoded: Option<&mut Option<Result<PortableTree, String>>>,
        trace: Option<&typed::MathmlTrace>,
    ) -> Result<String, String> {
        let (labelled, mut metadata) = typed::label(proof, definitions, decoded.is_some(), trace)?;
        if let Some(decoded) = decoded {
            *decoded = metadata.decoded_tree.take();
        }
        self.store_fragment(id, xml, &labelled, metadata);
        Ok(labelled)
    }

    fn label_with_tree(
        &mut self,
        id: u64,
        xml: &str,
        definitions: &mut HashMap<String, String>,
        decoded: Option<&mut Option<Result<PortableTree, String>>>,
    ) -> Result<String, String> {
        if let Some(labelled) = self.lookup(id, xml, definitions) {
            return Ok(labelled);
        }
        self.label_with_tree_miss(id, xml, definitions, decoded)
    }

    fn label_with_tree_miss(
        &mut self,
        id: u64,
        xml: &str,
        definitions: &mut HashMap<String, String>,
        decoded: Option<&mut Option<Result<PortableTree, String>>>,
    ) -> Result<String, String> {
        #[cfg(test)]
        let parse_timing = profile::scope(profile::Phase::Parse);
        let wrapped = format!("<context xmlns:ml=\"{ML}\" xmlns=\"{WS}\">{xml}</context>");
        let document = roxmltree::Document::parse(&wrapped).map_err(|e| e.to_string())?;
        #[cfg(test)]
        drop(parse_timing);
        self.label_parsed(
            id,
            xml,
            document.root_element(),
            &wrapped,
            definitions,
            decoded,
        )
    }

    fn label_parsed(
        &mut self,
        id: u64,
        xml: &str,
        context: Node<'_, '_>,
        source: &str,
        definitions: &mut HashMap<String, String>,
        decoded: Option<&mut Option<Result<PortableTree, String>>>,
    ) -> Result<String, String> {
        // Observe the identifiers already decoded by the ordinary labeller.
        // No second XML walk or extra identifier validation is introduced.
        let mut metadata = FragmentContext {
            decode_tree: decoded.is_some(),
            ..Default::default()
        };
        #[cfg(test)]
        let label_timing = profile::scope(profile::Phase::Label);
        let labelled = label_parsed_fragment(context, source, definitions, Some(&mut metadata))?;
        if let Some(decoded) = decoded {
            *decoded = metadata.decoded_tree.take();
        }
        #[cfg(test)]
        drop(label_timing);
        self.store_fragment(id, xml, &labelled, metadata);
        Ok(labelled)
    }

    fn store_fragment(&mut self, id: u64, xml: &str, labelled: &str, metadata: FragmentContext) {
        #[cfg(test)]
        let _timing = profile::scope(profile::Phase::Payload);
        if metadata.cacheable {
            let mut entry = Fragment {
                source: xml.to_owned(),
                dependencies: metadata.dependencies,
                defined: metadata.defined,
                labelled: labelled.to_owned(),
                bytes: 0,
            };
            entry.bytes = std::mem::size_of::<Fragment>()
                + entry.source.capacity()
                + entry.labelled.capacity()
                + entry.dependencies.capacity() * std::mem::size_of::<(String, Option<String>)>()
                + entry
                    .dependencies
                    .iter()
                    .map(|(name, label)| {
                        name.capacity() + label.as_ref().map_or(0, String::capacity)
                    })
                    .sum::<usize>()
                + entry
                    .defined
                    .as_ref()
                    .map_or(0, |(name, label)| name.capacity() + label.capacity());
            if let Some(old) = self.entries.remove(&id) {
                self.bytes -= old.bytes;
            }
            if entry.bytes <= MAX_CACHED_BYTES {
                // Bounded payload rather than unbounded document history. A
                // budget reset changes cost only, never the generated source.
                if self.bytes + entry.bytes > MAX_CACHED_BYTES {
                    self.entries.clear();
                    self.bytes = 0;
                }
                self.bytes += entry.bytes;
                self.entries.insert(id, entry);
            }
        }
    }
}

#[derive(Default)]
pub(super) struct FragmentContext {
    pub(super) decode_tree: bool,
    pub(super) decoded_tree: Option<Result<PortableTree, String>>,
    pub(super) cacheable: bool,
    dependencies: HashMap<String, Option<String>>,
    pub(super) defined: Option<(String, String)>,
}
impl FragmentContext {
    pub(super) fn observe(&mut self, identity: String, definitions: &HashMap<String, String>) {
        if let std::collections::hash_map::Entry::Vacant(entry) = self.dependencies.entry(identity)
        {
            let value = definitions.get(entry.key()).cloned();
            entry.insert(value);
        }
    }
}

